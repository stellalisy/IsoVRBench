#!/usr/bin/env python3
"""Derive pairs.jsonl and prompts.jsonl from prompts.txt.

    python example_data/build.py

prompts.txt is the authored description of this folder. This reads it, checks
it against what is on disk, and writes the machine readable forms: pairs.jsonl
in the schema the corpus uses, and prompts.jsonl for IsoGen's --prompts.

Renders nothing and changes no clip. Run it after editing prompts.txt or after
adding or removing a prompt directory.
"""
import importlib.util
import json
import os
import random
import re
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
VID = os.path.join(HERE, "videos")

# Two prompts of the eight are validation. Held out whole, so no anchor appears
# on both sides of the split: the families re-pair the same anchor, and holding
# out a pair would leave both its clips in training under a different pairing.
N_VAL = 2

# rejected clip, preferred clip, dimensions the pair labels, how it was built.
# Only the dimensions an intervention licenses are labelled. mq_hold rearranges
# the anchor's own pixels, so it says nothing about visual quality.
FAMILIES = [
    ("vq_steps", "vq_steps_k8.mp4", "s50.mp4", ["VQ"],
     "8 denoising steps instead of 50; same model, prompt and seed"),
    ("size_1p3b", "size_1p3b.mp4", "s50.mp4", ["VQ", "MQ"],
     "rendered by Wan2.1-T2V-1.3B from the same prompt"),
    ("size_5b", "size_5b.mp4", "s50.mp4", ["VQ", "MQ"],
     "rendered by Wan2.2-TI2V-5B from the same prompt, unconditioned"),
    ("size_i2v", "size_i2v.mp4", "s50.mp4", ["VQ", "MQ"],
     "rendered by Wan2.2-TI2V-5B conditioned on the anchor's first frame"),
    ("mq_gen", "mq_gen.mp4", "s50.mp4", ["MQ"],
     "keyframes kept, gaps regenerated by I2V and snapped back to the next "
     "real keyframe"),
    ("mq_hold", "mq_hold.mp4", "s50.mp4", ["MQ"],
     "real frames of the anchor held for several frame durations"),
    ("shuffle", "shuffle.mp4", "s50.mp4", ["MQ"],
     "the anchor cut into six contiguous segments and reordered"),
    ("ta_attrib", "ta_attrib.mp4", "s50.mp4", ["TA"],
     "attributes edited in the prompt, then judged against the original prompt"),
]


def _mod(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    sys.modules[name] = m
    spec.loader.exec_module(m)
    return m


def parse_prompts(path):
    """pXXXXXX blocks with prompt, edited and order fields."""
    out, pid = {}, None
    for line in open(path):
        m = re.match(r"^(p\d{6})\s*$", line)
        if m:
            pid = m.group(1)
            out[pid] = {}
            continue
        if not pid:
            continue
        m = re.match(r"^\s+(prompt|edited)\s+(.*\S)\s*$", line)
        if m:
            out[pid][m.group(1)] = m.group(2)
            continue
        m = re.match(r"^\s+order\s+segments\s+([\d ]+?)\s*\(", line)
        if m:
            out[pid]["order"] = [int(x) for x in m.group(1).split()]
    return out


def main():
    pr = parse_prompts(os.path.join(HERE, "prompts.txt"))
    pids = sorted(d for d in os.listdir(VID)
                  if os.path.isdir(os.path.join(VID, d)))
    if set(pr) != set(pids):
        sys.exit("prompts.txt and videos/ disagree: %s"
                 % sorted(set(pr) ^ set(pids)))
    print("%d prompts" % len(pids))

    # Every prompt here is meant to carry every family. Say so loudly if one
    # does not, rather than quietly writing a short file.
    short = {}
    for pid in pids:
        have = set(os.listdir(os.path.join(VID, pid)))
        absent = [rej for _, rej, keep, _, _ in FAMILIES
                  if rej not in have or keep not in have]
        if absent:
            short[pid] = absent
    if short:
        for pid, a in sorted(short.items()):
            print("  %s is missing %s" % (pid, ", ".join(a)))
        sys.exit("every prompt should carry all eight families")

    # shuffle is filtered on motion when the corpus is built, because
    # reordering a clip that barely moves changes nothing a person could see.
    sys.path.insert(0, os.path.join(REPO, "IsoGen"))
    gc = _mod("config", os.path.join(REPO, "IsoGen", "config.py"))
    IV = _mod("interventions", os.path.join(REPO, "IsoGen", "interventions.py"))
    gen = _mod("generate", os.path.join(REPO, "IsoGen", "generate.py"))
    cfg = gc.load("benchmark")

    motion = {}
    for pid in pids:
        f = gen.read_frames(os.path.join(VID, pid, "s50.mp4"))
        motion[pid] = round(IV.motion_score(f), 2)
    low = sorted(p for p in pids if motion[p] < cfg.shuffle_motion_min)
    if low:
        sys.exit("below shuffle_motion_min of %.1f: %s"
                 % (cfg.shuffle_motion_min,
                    ", ".join("%s %.1f" % (p, motion[p]) for p in low)))
    print("motion %.1f to %.1f, all clear the floor of %.1f"
          % (min(motion.values()), max(motion.values()), cfg.shuffle_motion_min))

    val = set(random.Random(0).sample(pids, N_VAL))

    recs, n = [], 0
    for fam, rej, keep, dims, how in FAMILIES:
        # half of each family puts the preferred clip on A, so answering the
        # same side every time scores 50 and position carries no signal
        on_a = set(random.Random(fam).sample(pids, len(pids) // 2))
        for pid in pids:
            prompt = pr[pid]["prompt"]
            good, bad = "%s/%s" % (pid, keep), "%s/%s" % (pid, rej)
            good_is_a = pid in on_a
            a, b = (good, bad) if good_is_a else (bad, good)
            rec = {
                "id": "%s-%06d" % (fam, n),
                "split": "val" if pid in val else "train",
                "intervention": fam,
                "prompt": prompt,
                "video_a": {"path": a, "prompt": prompt},
                "video_b": {"path": b, "prompt": prompt},
                "preferred": {d: ("A" if good_is_a else "B") for d in dims},
                "construction": how,
                "prompt_id": pid,
            }
            if fam == "shuffle":
                rec["motion"] = motion[pid]
                if "order" in pr[pid]:
                    rec["segment_order"] = pr[pid]["order"]
            if fam == "ta_attrib":
                rec["edited_prompt"] = pr[pid]["edited"]
            recs.append(rec)
            n += 1

    with open(os.path.join(HERE, "pairs.jsonl"), "w") as f:
        for r in recs:
            f.write(json.dumps(r) + "\n")
    with open(os.path.join(HERE, "prompts.jsonl"), "w") as f:
        for pid in pids:
            d = {"pid": pid, "prompt": pr[pid]["prompt"]}
            if "edited" in pr[pid]:
                d["edited"] = pr[pid]["edited"]
            f.write(json.dumps(d) + "\n")

    side = Counter(r["preferred"][next(iter(r["preferred"]))] for r in recs)
    print("%d pairs, %d train, %d val"
          % (len(recs), sum(r["split"] == "train" for r in recs),
             sum(r["split"] == "val" for r in recs)))
    print("by family:", dict(Counter(r["intervention"] for r in recs)))
    print("by label :", dict(Counter(d for r in recs for d in r["preferred"])))
    print("preferred side: A %d, B %d" % (side["A"], side["B"]))
    print("wrote pairs.jsonl and prompts.jsonl")


if __name__ == "__main__":
    main()
